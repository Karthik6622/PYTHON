"""GitHub workflows: link a repository, commit generated tests, import tests, open pull requests for verified locator fixes."""

from __future__ import annotations

import re
from collections.abc import Callable
from typing import Any

import httpx

from ats.ai.agents import GitHubAgent
from ats.analysis.patching import LOCATOR_FILE, patch_locators
from ats.automation.bundle_store import BundleStore, import_files, is_secret
from ats.errors import GitHubError, NotFoundError, StudioError
from ats.execution.executor import ExecutionContext
from ats.github.client import GitHubClient, parse_repo, valid_branch
from ats.logging_setup import get_logger
from ats.models import Selector, utc_now
from ats.repository import Project, Repository

LOGGER = get_logger("github.service")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:30] or "project"


class GitHubService:
    def __init__(self, repo: Repository, store: BundleStore | None = None, agent: GitHubAgent | None = None, transport: httpx.BaseTransport | None = None) -> None:
        self.repo = repo
        self.store = store or BundleStore()
        self.agent = agent or GitHubAgent(repository=repo)
        self.transport = transport

    def client(self, token: str) -> GitHubClient:
        return GitHubClient(token, transport=self.transport)

    # ------------------------------------------------------------------ link / import
    def link(self, project: Project, repo_url: str, token: str) -> dict[str, Any]:
        owner, name = parse_repo(repo_url)
        client = self.client(token)
        try:
            info = client.get_repo(owner, name)
            branches = client.list_branches(owner, name)
        finally:
            client.close()
        self.repo.save_github(project.id, repo_url=f"https://github.com/{owner}/{name}", default_branch=info["default_branch"])
        self.repo.audit(project.id, "user", "github.linked", "github", {"repo": info["full_name"], "can_push": info["can_push"]})
        return {**info, "branches": branches}

    def import_tests(self, project: Project, token: str, ref: str = "") -> tuple[dict[str, str], str]:
        """Download the repository at ``ref``. Returns (text files without secrets, ref used)."""
        link = self.repo.get_github(project.id)
        if not link or not link.get("repo_url"):
            raise GitHubError("Link a GitHub repository first.")
        owner, name = parse_repo(link["repo_url"])
        ref = ref or link.get("branch") or link.get("default_branch") or "main"
        client = self.client(token)
        try:
            raw = client.download_files(owner, name, ref)
        finally:
            client.close()
        files = import_files(raw)
        if not files:
            raise GitHubError("No usable test files were found in that repository.")
        self.repo.audit(project.id, "user", "github.imported", "github", {"ref": ref, "files": len(files)})
        return files, ref

    # ------------------------------------------------------------------ text
    def _text(self, project: Project, kind: str, framework: str, tests: list[dict[str, str]], changes: list[dict[str, Any]] | None = None) -> dict[str, str]:
        stamp = utc_now()[:10].replace("-", "")
        prefix = "ai-tests" if kind == "tests" else "ai-heal"
        fallback = {
            "branch_name": f"{prefix}/{_slug(project.name)}-{stamp}-{utc_now()[11:19].replace(':', '')}",
            "commit_title": f"Add AI-generated {framework} tests for {project.name}" if kind == "tests" else f"Update locators for {project.name} (verified by rerun)",
            "commit_body": "Generated by AI Autonomous Testing Studio. Review before merging.",
            "pr_title": f"AI-generated tests for {project.name}" if kind == "tests" else f"Locator fixes for {project.name}",
            "pr_body": "",
        }
        try:
            text = self.agent.describe({"kind": kind, "project_name": project.name, "framework": framework, "test_cases": tests[:60], "changes": changes or []}, project.id)
        except StudioError:
            return fallback
        branch = text.branch_name.strip().lower()
        if not (valid_branch(branch) and branch.startswith(f"{prefix}/")):
            branch = fallback["branch_name"]
        else:  # keep branches unique per commit
            branch = f"{branch[:60].rstrip('-/')}-{utc_now()[11:19].replace(':', '')}"
        return {
            "branch_name": branch, "commit_title": (text.commit_title or fallback["commit_title"])[:72],
            "commit_body": text.commit_body or fallback["commit_body"], "pr_title": text.pr_title or fallback["pr_title"], "pr_body": text.pr_body,
        }  # fmt: skip

    # ------------------------------------------------------------------ commit generated tests
    def commit_bundle(self, project: Project, bundle_id: int, token: str, *, open_pr: bool = True, branch: str = "", base_branch: str = "", path_prefix: str = "") -> dict[str, Any]:
        link = self.repo.get_github(project.id)
        if not link or not link.get("repo_url"):
            raise GitHubError("Link a GitHub repository first.")
        bundle = self.repo.get_bundle(bundle_id)
        if not bundle or bundle["project_id"] != project.id:
            raise NotFoundError()
        files = {rel: text for rel, text in self.store.read_all(project.id, bundle_id).items() if not is_secret(rel)}
        prefix = path_prefix.strip("/")
        if prefix:
            files = {f"{prefix}/{rel}": text for rel, text in files.items()}
        owner, name = parse_repo(link["repo_url"])
        base = base_branch or link.get("default_branch") or "main"
        cases = [{"id": t["test_case_id"], "title": t.get("title", "")} for t in bundle["traceability"] if t.get("test_case_id")]
        text = self._text(project, "tests", bundle["framework"], cases)
        branch = branch.strip() or text["branch_name"]
        client = self.client(token)
        try:
            info = client.get_repo(owner, name)
            if not info["can_push"]:
                raise GitHubError("The token cannot push to this repository.")
            if branch == base or branch == info["default_branch"]:
                raise GitHubError("Tests are committed to a new branch, never directly to the default branch.")
            result = client.commit_files(owner, name, branch=branch, base_branch=base, files=files, message=f"{text['commit_title']}\n\n{text['commit_body']}".strip())
            pr: dict[str, Any] = {}
            if open_pr:
                body = text["pr_body"] or self._tests_pr_body(project, bundle, cases)
                pr = client.open_pull_request(owner, name, head=branch, base=base, title=text["pr_title"], body=body)
        finally:
            client.close()
        self.repo.save_github(project.id, branch=branch, commit_sha=result["commit_sha"], branch_url=result["branch_url"], commit_url=result["commit_url"], pr_url=pr.get("url", ""), bundle_id=bundle_id)
        self.repo.update_bundle(bundle_id, status="committed")
        self.repo.audit(project.id, "user", "github.committed", "github", {"branch": branch, "commit": result["commit_sha"][:10], "files": len(files), "pr": pr.get("url", "")})
        return {**result, "branch": branch, "pr_url": pr.get("url", ""), "files": len(files)}

    @staticmethod
    def _tests_pr_body(project: Project, bundle: dict[str, Any], cases: list[dict[str, str]]) -> str:
        rows = "\n".join(f"| {c['id']} | {c['title']} |" for c in cases[:80])
        return (
            f"Automated tests for **{project.name}** generated by AI Autonomous Testing Studio.\n\n"
            f"* Framework: `{bundle['framework']}`\n* Browser: `{bundle['browser']}`\n* Test cases: {len(cases)}\n\n"
            f"| Test case | Title |\n| --- | --- |\n{rows}\n\nPlease review the generated code and locators before merging."
        )

    # ------------------------------------------------------------------ verified locator fixes
    def open_healing_pr(self, ctx: ExecutionContext, healing_ids: list[int], token: str) -> str:
        """Open a pull request that changes only ``config/locators.json``. Returns the pull request URL."""
        project = ctx.project
        link = self.repo.get_github(project.id)
        if not link or not link.get("repo_url"):
            raise GitHubError("Link a GitHub repository first.")
        records = [r for r in (self.repo.get_healing(i) for i in healing_ids) if r and r["status"] in {"verified", "applied"}]
        if not records:
            raise GitHubError("There are no verified fixes to submit.")
        execution = self.repo.get_execution(ctx.execution_id) or {}
        files = dict(ctx.files)
        selenium = ctx.framework.startswith("selenium")
        for record in records:
            files, _, _ = patch_locators(files, record["element_key"], Selector.model_validate(record["new_locator"]), selenium)
        owner, name = parse_repo(link["repo_url"])
        base = execution.get("branch") or link.get("branch") or link.get("default_branch") or "main"
        changes = [{"element": r["element_key"], "old": r["old_locator"], "new": r["new_locator"], "confidence": r["confidence"]} for r in records]
        text = self._text(project, "heal", ctx.framework, [], changes)
        client = self.client(token)
        try:
            if not client.get_repo(owner, name)["can_push"]:
                raise GitHubError("The token cannot push to this repository.")
            result = client.commit_files(owner, name, branch=text["branch_name"], base_branch=base, files={LOCATOR_FILE: files[LOCATOR_FILE]}, message=f"{text['commit_title']}\n\n{text['commit_body']}".strip())
            pr = client.open_pull_request(owner, name, head=text["branch_name"], base=base, title=text["pr_title"], body=text["pr_body"] or self._healing_pr_body(ctx, records))
        finally:
            client.close()
        for record in records:
            self.repo.update_healing(record["id"], status="pr_opened", pr_url=pr["url"])
        self.repo.audit(project.id, "system", "github.heal_pr", "github", {"pr": pr["url"], "fixes": [r["id"] for r in records], "commit": result["commit_sha"][:10]})
        return pr["url"]

    @staticmethod
    def _healing_pr_body(ctx: ExecutionContext, records: list[dict[str, Any]]) -> str:
        rows = "\n".join(
            f"| `{r['element_key']}` | `{_selector_text(r['old_locator'])}` | `{_selector_text(r['new_locator'])}` | {r['confidence']:.2f} | {', '.join(r['test_case_ids'])} |" for r in records
        )
        return (
            "## Locator fixes proposed by self-healing\n\n"
            f"Execution `{ctx.execution_id}`. Each fix was validated against the failing page, then the affected tests were re-run with only this change.\n"
            "Tests are reported as **HEALED**, not passed: please confirm the new elements are the intended ones.\n\n"
            f"| Element | Old | New | Confidence | Tests |\n| --- | --- | --- | --- | --- |\n{rows}\n\n"
            "Only `config/locators.json` changes. No assertions, test data or test logic were modified."
        )

    def pr_callback(self, token_provider: Callable[[], str]) -> Callable[[ExecutionContext, list[int]], None]:
        """Callback for AnalysisService (policy ``auto_pr``). Does nothing when no token is available in the session."""

        def on_verified(ctx: ExecutionContext, healing_ids: list[int]) -> None:
            token = token_provider()
            if not token:
                self.repo.audit(ctx.project.id, "system", "github.heal_pr_skipped", "github", {"reason": "no token in session"})
                return
            self.open_healing_pr(ctx, healing_ids, token)

        return on_verified


def _selector_text(data: dict[str, Any]) -> str:
    try:
        return Selector.model_validate(data).display()
    except ValueError:
        return str(data)
